def configure_opencode_in_sandbox(
    model_name: str,
    sandbox_name: str = SANDBOX_NAME,
    llm_base_url: str = DEFAULT_LLM_BASE_URL,
) -> None:
    """Write opencode.json configuration inside the sandbox container."""
    config_data = {
        "$schema": "https://opencode.ai/config.json",
        "share": "disabled",
        "permission": {
            "*": "allow"
        },
        "provider": {
            "sparky": {
                "name": "sparky",
                "npm": "@ai-sdk/openai-compatible",
                "options": {
                    "baseURL": llm_base_url,
                    "apiKey": "dummy",
                },
                "models": {
                    model_name: {
                        "name": model_name,
                        "modalities": {
                            "input": ["text", "image"],
                            "output": ["text"],
                        },
                    },
                },
            },
        },
    }
    config_json = json.dumps(config_data, indent=2)
    setup_cmd = f"mkdir -p ~/.config/opencode && cat << 'EOF' > ~/.config/opencode/opencode.json\n{config_json}\nEOF"
    exec_in_sandbox(sandbox_name, setup_cmd)


def start_opencode_server_in_workspace(
    sandbox_name: str,
    work_dir: str,
    port: int = OPENCODE_PORT,
) -> None:
    """Start OpenCode server anchored in a specific working directory."""
    print(f"--> Starting OpenCode server inside workspace {work_dir} on port {port}...")
    run_server_cmd = (
        f"killall opencode 2>/dev/null || true; "
        f"export PATH=$HOME/.opencode/bin:$HOME/.local/bin:$PATH; "
        f"cd {work_dir} && (nohup opencode serve --port {port} --hostname 0.0.0.0 --print-logs --log-level DEBUG </dev/null >/tmp/opencode_server.log 2>&1 & disown)"
    )
    exec_in_sandbox(sandbox_name, run_server_cmd)

    # Health check via python inside sandbox
    check_script = f"""import urllib.request
try:
    res = urllib.request.urlopen('http://127.0.0.1:{port}/global/health', timeout=2)
    print('OK')
except Exception:
    try:
        res = urllib.request.urlopen('http://127.0.0.1:{port}/session', timeout=2)
        print('OK')
    except Exception:
        print('WAIT')
"""
    for _ in range(30):
        res = subprocess.run(["sbx", "exec", sandbox_name, "python3", "-c", check_script], capture_output=True, text=True)
        if "OK" in res.stdout:
            print(f"✓ OpenCode server responsive inside sandbox at http://127.0.0.1:{port}")
            return
        time.sleep(0.5)

    print("Warning: OpenCode server took longer than expected to respond.", file=sys.stderr)


def create_session_in_sandbox(sandbox_name: str, port: int = OPENCODE_PORT) -> str:
    """Create a new session in the OpenCode server directly inside the sandbox container."""
    script = f"""import urllib.request, json
req = urllib.request.Request('http://127.0.0.1:{port}/session', data=b'{{}}', headers={{'Content-Type': 'application/json'}})
res = urllib.request.urlopen(req, timeout=30)
data = json.loads(res.read().decode('utf-8'))
print(data['id'])
"""
    res = subprocess.run(["sbx", "exec", sandbox_name, "python3", "-c", script], capture_output=True, text=True, check=True)
    return res.stdout.strip()


def send_message_in_sandbox(
    sandbox_name: str,
    session_id: str,
    prompt: str,
    model_name: str,
    provider_id: str = "sparky",
    port: int = OPENCODE_PORT,
    timeout: int = 1200,
) -> dict[str, Any]:
    """Send task prompt to OpenCode server directly inside the sandbox container."""
    payload_json = json.dumps({
        "parts": [{"type": "text", "text": prompt}],
        "model": {
            "providerID": provider_id,
            "modelID": model_name,
        },
    })

    script = f"""import urllib.request, json, sys
payload = sys.stdin.read().encode('utf-8')
req = urllib.request.Request(
    'http://127.0.0.1:{port}/session/{session_id}/message',
    data=payload,
    headers={{'Content-Type': 'application/json'}}
)
try:
    res = urllib.request.urlopen(req, timeout={timeout})
    print("__JSON_START__" + res.read().decode('utf-8') + "__JSON_END__")
except urllib.error.HTTPError as e:
    err_body = e.read().decode('utf-8', errors='replace')
    print(f"HTTP_ERROR:{{e.code}}:{{err_body}}", file=sys.stderr)
    sys.exit(1)
"""
    cmd = ["sbx", "exec", sandbox_name, "python3", "-c", script]
    res = subprocess.run(cmd, input=payload_json, capture_output=True, text=True)
    if res.returncode != 0:
        raise RuntimeError(f"OpenCode in-sandbox execution error (code {res.returncode}): {res.stderr}\n{res.stdout}")

    match = re.search(r"__JSON_START__(.*?)__JSON_END__", res.stdout, re.DOTALL)
    if not match:
        raise RuntimeError(f"Could not parse OpenCode response JSON: {res.stdout}\nStderr: {res.stderr}")
    return json.loads(match.group(1))


def get_session_messages_in_sandbox(
    sandbox_name: str,
    session_id: str,
    port: int = OPENCODE_PORT,
) -> list[dict[str, Any]]:
    """Retrieve all chronological messages, tool calls, and parts from the OpenCode session."""
    script = f"""import urllib.request, json
try:
    req = urllib.request.Request('http://127.0.0.1:{port}/session/{session_id}/message')
    res = urllib.request.urlopen(req, timeout=30)
    data = json.loads(res.read().decode('utf-8'))
    print("__JSON_START__" + json.dumps(data) + "__JSON_END__")
except Exception as e:
    print(f"ERROR:{{e}}", file=sys.stderr)
"""
    cmd = ["sbx", "exec", sandbox_name, "python3", "-c", script]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode == 0:
        match = re.search(r"__JSON_START__(.*?)__JSON_END__", res.stdout, re.DOTALL)
        if match:
            return json.loads(match.group(1))
    return []


