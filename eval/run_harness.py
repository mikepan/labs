def load_test_spec(test_name_or_path: str):
    """Load a TestSpec from a test directory or run.py file."""
    if os.path.isdir(test_name_or_path):
        target_file = os.path.join(test_name_or_path, "run.py")
    elif os.path.isfile(test_name_or_path):
        target_file = test_name_or_path
    else:
        candidate = os.path.join(REPO_ROOT, "tests", test_name_or_path, "run.py")
        if os.path.isfile(candidate):
            target_file = candidate
        else:
            raise FileNotFoundError(f"Cannot find test file for '{test_name_or_path}'")

    spec = importlib.util.spec_from_file_location("test_module", target_file)
    if spec is None or spec.loader is None:
        raise ImportError(f"Could not load spec from {target_file}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if hasattr(module, "TEST"):
        return module.TEST
    raise AttributeError(f"Module {target_file} has no 'TEST' object defined.")


def evaluate_step_in_sandbox(
    sandbox_name: str,
    test_run_file: str,
    step_idx: int,
    workspace_dir_in_sandbox: str,
) -> dict[str, Any]:
    """Execute step assertions directly inside the sandbox container."""
    eval_script = f"""import json, sys, importlib.util
sys.path.insert(0, '{REPO_ROOT}')
from tests.framework.runner import evaluate_step

spec = importlib.util.spec_from_file_location('test_mod', '{test_run_file}')
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)
test = mod.TEST
step = test.steps[{step_idx}]

res = evaluate_step(step, '{workspace_dir_in_sandbox}')
output = {{
    "step_name": res.step_name,
    "passed": res.passed,
    "point": getattr(res, "point", getattr(step, "point", 1)),
    "score": getattr(res, "score", (getattr(step, "point", 1) if res.passed else 0)),
    "duration_seconds": res.duration_seconds,
    "check_results": [
        {{"passed": c.passed, "message": c.message, "details": c.details}}
        for c in res.check_results
    ]
}}
print("__JSON_START__" + json.dumps(output) + "__JSON_END__")
"""
    full_cmd = ["sbx", "exec", sandbox_name, "python3"]
    res = subprocess.run(full_cmd, input=eval_script, capture_output=True, text=True)

    if res.returncode != 0 or "__JSON_START__" not in res.stdout:
        return {
            "step_name": f"Step {step_idx}",
            "passed": False,
            "point": 1,
            "score": 0,
            "duration_seconds": 0.0,
            "check_results": [{"passed": False, "message": f"Evaluation runner error (code {res.returncode}): {res.stderr}\n{res.stdout}"}],
        }

    match = re.search(r"__JSON_START__(.*?)__JSON_END__", res.stdout, re.DOTALL)
    if match:
        return json.loads(match.group(1))
    return {
        "step_name": f"Step {step_idx}",
        "passed": False,
        "point": 1,
        "score": 0,
        "duration_seconds": 0.0,
        "check_results": [{"passed": False, "message": f"Could not parse evaluation json: {res.stdout}"}],
    }


def run_test_suite_on_agent(
    model_name: str,
    test_specs: list[tuple[str, Any]],
    sandbox_name: str = SANDBOX_NAME,
) -> dict[str, Any]:
    """Execute all test specs sequentially against OpenCode inside the sandbox."""
    stage_dir = tempfile.mkdtemp(prefix="eval_artifacts_")
    suite_trace = {
        "model": model_name,
        "start_time": datetime.now(timezone.utc).isoformat(),
        "tests": {},
    }
    test_results_summary = {}

    for test_path, test_obj in test_specs:
        test_id = test_obj.name
        logger.info("RUNNING TEST: %s (%d steps)", test_id, len(test_obj.steps))

        test_ws_in_sandbox = f"/tmp/eval_{test_id}"
        # Clean and setup test workspace in sandbox
        exec_in_sandbox(sandbox_name, f"rm -rf {test_ws_in_sandbox} && mkdir -p {test_ws_in_sandbox}")
        for cmd in test_obj.setup:
            exec_in_sandbox(sandbox_name, f"cd {test_ws_in_sandbox} && {cmd}")

        logger.debug("Initialized workspace: %s", test_ws_in_sandbox)

        # Start OpenCode server in workspace
        start_opencode_server_in_workspace(sandbox_name, test_ws_in_sandbox)
        session_id = create_session_in_sandbox(sandbox_name)
        logger.info("OpenCode session created: %s", session_id)

        test_start_time = time.time()
        step_traces = []
        passed_steps = 0
        max_score = sum(getattr(s, "point", 1) for s in test_obj.steps)
        earned_score = 0
        total_tokens_in = 0
        total_tokens_out = 0

        for idx, step in enumerate(test_obj.steps):
            step_name = step.name or f"Step {idx + 1}"
            step_point = getattr(step, "point", 1)
            logger.info("--- [Step %d/%d] %s (point=%d) ---", idx + 1, len(test_obj.steps), step_name, step_point)
            logger.debug("Prompt: %s...", step.prompt.strip()[:100])

            # Check messages count before prompt
            msgs_before = get_session_messages_in_sandbox(sandbox_name, session_id)
            prev_count = len(msgs_before)

            step_t0 = time.time()
            agent_response = send_message_in_sandbox(
                sandbox_name=sandbox_name,
                session_id=session_id,
                prompt=step.prompt,
                model_name=model_name,
            )
            step_elapsed = round(time.time() - step_t0, 2)

            # Retrieve all messages after prompt
            msgs_after = get_session_messages_in_sandbox(sandbox_name, session_id)
            step_messages = msgs_after[prev_count:] if len(msgs_after) > prev_count else [agent_response]

            # Extract tool calls & reasoning across all messages in this turn
            turn_tool_calls = []
            turn_reasoning = []
            turn_text = []

            for msg in step_messages:
                parts = msg.get("parts", [])
                for p in parts:
                    p_type = p.get("type")
                    if p_type == "reasoning" and p.get("text"):
                        turn_reasoning.append(p.get("text"))
                    elif p_type == "text" and p.get("text") and msg.get("info", {}).get("role") == "assistant":
                        turn_text.append(p.get("text"))
                    elif p_type == "tool":
                        state = p.get("state", {})
                        t_time = state.get("time", {})
                        dur_ms = (t_time.get("end", 0) - t_time.get("start", 0)) if t_time else None
                        turn_tool_calls.append({
                            "tool": p.get("tool"),
                            "call_id": p.get("callID"),
                            "status": state.get("status"),
                            "input": state.get("input"),
                            "output": state.get("output"),
                            "exit_code": state.get("metadata", {}).get("exit"),
                            "duration_ms": dur_ms,
                        })
                    elif p_type == "step-finish":
                        toks = p.get("tokens", {})
                        total_tokens_in += toks.get("input", 0)
                        total_tokens_out += toks.get("output", 0)

            # Log reasoning & tool calls
            if turn_reasoning:
                logger.debug("[Reasoning]: %s...", turn_reasoning[-1].strip()[:140])
            for tc in turn_tool_calls:
                inp_summary = str(tc.get("input", {}))
                if len(inp_summary) > 80:
                    inp_summary = inp_summary[:77] + "..."
                logger.info("  [Tool Call]: %s -> %s", tc.get("tool"), inp_summary)
            if turn_text:
                logger.debug("[Response]: %s...", turn_text[-1].strip()[:140])

            # Run step assertions in sandbox
            eval_res = evaluate_step_in_sandbox(
                sandbox_name,
                test_path,
                idx,
                test_ws_in_sandbox,
            )

            passed = eval_res.get("passed", False)
            step_score = eval_res.get("score", (step_point if passed else 0))
            earned_score += step_score

            if passed:
                passed_steps += 1
                logger.info("  ✓ Step %d PASSED (+%d/%d pts) (%.2fs)", idx + 1, step_score, step_point, step_elapsed)
            else:
                logger.warning("  ✗ Step %d FAILED (0/%d pts) (%.2fs)", idx + 1, step_point, step_elapsed)
                for cr in eval_res.get("check_results", []):
                    if not cr.get("passed"):
                        logger.warning("    - Failure: %s", cr.get("message"))

            # Record step trace
            step_traces.append({
                "step_index": idx,
                "step_name": step_name,
                "prompt": step.prompt,
                "point": step_point,
                "earned_score": step_score,
                "max_score": step_point,
                "tool_calls": turn_tool_calls,
                "reasoning_blocks": turn_reasoning,
                "response_text": "\n\n".join(turn_text),
                "messages": step_messages,
                "evaluation": eval_res,
                "duration_seconds": step_elapsed,
            })

        test_duration = round(time.time() - test_start_time, 2)
        trace_id = str(uuid.uuid4())
        
        # Determine context length dynamically to compute true context_used_pct
        max_ctx = get_model_context_length(base_url=DEFAULT_LLM_BASE_URL)
        total_tokens = total_tokens_in + total_tokens_out
        context_used_pct = round((total_tokens / max_ctx) * 100.0, 2) if max_ctx > 0 else 0.0

        test_results_summary[test_id] = {
            "name": test_obj.description or test_id,
            "earned_score": earned_score,
            "max_score": max_score,
            "run_time_sec": test_duration,
            "tokens_in": total_tokens_in,
            "tokens_out": total_tokens_out,
            "context_used_pct": context_used_pct,
            "trace_id": trace_id,
        }

        # Extract generated artifacts from sandbox workspace to temporary staging directory
        local_artifacts_stage = os.path.join(stage_dir, test_id)
        os.makedirs(local_artifacts_stage, exist_ok=True)
        tar_cmd = f"cd {test_ws_in_sandbox} && tar --exclude='.git' -cf - ."
        res = subprocess.run(["sbx", "exec", sandbox_name, "bash", "-c", tar_cmd], capture_output=True)
        if res.returncode == 0 and res.stdout:
            subprocess.run(["tar", "-xf", "-", "-C", local_artifacts_stage], input=res.stdout, capture_output=True)

        # Extract opencode_server.log from sandbox to staging dir
        res_log = subprocess.run(["sbx", "exec", sandbox_name, "cat", "/tmp/opencode_server.log"], capture_output=True, text=True)
        if res_log.returncode == 0 and res_log.stdout:
            with open(os.path.join(stage_dir, "opencode_server.log"), "w", encoding="utf-8") as f:
                f.write(res_log.stdout)

        session_info = get_session_info_in_sandbox(sandbox_name, session_id)
        all_session_messages = get_session_messages_in_sandbox(sandbox_name, session_id)

        completion_rate = round((earned_score / max_score) * 100.0, 1) if max_score > 0 else 100.0
        suite_trace["tests"][test_id] = {
            "trace_id": trace_id,
            "completion_rate": completion_rate,
            "earned_score": earned_score,
            "max_score": max_score,
            "passed_steps": passed_steps,
            "total_steps": len(test_obj.steps),
            "duration_seconds": test_duration,
            "session_id": session_id,
            "session_info": session_info,
            "steps": step_traces,
            "all_session_messages": all_session_messages,
        }

        logger.info("✓ Test '%s' complete: score %d/%d (%.1f%%) in %.2fs", test_id, earned_score, max_score, completion_rate, test_duration)

    suite_trace["end_time"] = datetime.now(timezone.utc).isoformat()
    return {
        "suite_trace": suite_trace,
        "test_results_summary": test_results_summary,
        "stage_dir": stage_dir,
    }


