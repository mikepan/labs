def get_model_metadata(model_name: str) -> dict[str, Any]:
    """Retrieve metadata from models.json or generate standard defaults."""
    if os.path.exists(MODELS_FILE):
        with open(MODELS_FILE, "r", encoding="utf-8") as f:
            models = json.load(f)
            if model_name in models:
                cfg = models[model_name]
                spec_arg = cfg.get("model-arg-speculative", "")
                kv_arg = cfg.get("model-arg-kv-quant", "")
                launch_cfg = cfg.get("model-arg", "")

                spec_type = "off"
                if spec_arg:
                    m = re.search(r'"method":\s*"([^"]+)"', spec_arg)
                    spec_type = m.group(1) if m else "on"

                kv_type = "FP16"
                if kv_arg:
                    m = re.search(r"--kv-cache-dtype\s+(\S+)", kv_arg)
                    kv_type = m.group(1).upper() if m else kv_arg

                quant = "FP8" if "FP8" in model_name or "NVFP4" in model_name else "Q4_K_M"
                if "NVFP4" in model_name:
                    quant = "NVFP4"

                return {
                    "display_name": "Qwen3.6 27B FP8" if "27B" in model_name else model_name,
                    "company": "Qwen" if "qwen" in model_name.lower() else "Nvidia",
                    "parent_model": model_name,
                    "model_quant": quant,
                    "kv_quant": kv_type,
                    "param_size_b": 27 if "27B" in model_name else 35,
                    "model_size_gb": 28.0,
                    "context_length": 32768,
                    "release_date": "2026-02-05",
                    "speculative_decoding": spec_type,
                    "launch_config": launch_cfg,
                }

    return {
        "display_name": model_name,
        "company": "Community",
        "parent_model": model_name,
        "model_quant": "FP8",
        "kv_quant": "FP8",
        "param_size_b": 27,
        "model_size_gb": 28.0,
        "context_length": 32768,
        "release_date": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "speculative_decoding": "off",
        "launch_config": "vllm serve",
    }


def save_evaluation_results(
    model_name: str,
    harness_name: str,
    harness_version: str,
    evaluation_output: dict[str, Any],
) -> str:
    """Save full results, trace, artifacts and update benchmark-data.json."""
    timestamp_str = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    model_slug = re.sub(r"[^a-zA-Z0-9_-]", "_", model_name.replace("/", "_")).lower()
    eval_name = f"{model_slug}_{harness_name}_{timestamp_str}"
    eval_dir = os.path.join(RESULTS_DIR, eval_name)
    artifacts_dir = os.path.join(eval_dir, "artifacts")

    os.makedirs(artifacts_dir, exist_ok=True)

    suite_trace = evaluation_output["suite_trace"]
    test_results_summary = evaluation_output["test_results_summary"]

    # 1. Copy artifacts from staging to results/{eval_name}/
    stage_root = os.path.join(REPO_ROOT, "scratch", "artifacts_stage")
    if os.path.exists(stage_root):
        for item in os.listdir(stage_root):
            src = os.path.join(stage_root, item)
            if item == "opencode_server.log":
                shutil.copy2(src, os.path.join(eval_dir, "opencode_server.log"))
            elif os.path.isdir(src):
                dst = os.path.join(artifacts_dir, item)
                shutil.copytree(src, dst, dirs_exist_ok=True)
            else:
                dst = os.path.join(artifacts_dir, item)
                shutil.copy2(src, dst)
        shutil.rmtree(stage_root, ignore_errors=True)

    # 2. Save full_trace.json
    trace_path = os.path.join(eval_dir, "full_trace.json")
    with open(trace_path, "w", encoding="utf-8") as f:
        json.dump(suite_trace, f, indent=2)

    # 3. Calculate aggregate scores
    meta = get_model_metadata(model_name)
    total_completion = 0.0
    total_time = 0.0
    num_tests = len(test_results_summary)
    for t_data in test_results_summary.values():
        total_completion += t_data.get("run_completion", 0.0)
        total_time += t_data.get("run_time_sec", 1.0)

    avg_completion = round(total_completion / num_tests, 1) if num_tests > 0 else 0.0
    task_speed = round((num_tests / (total_time / 3600.0)), 1) if total_time > 0 else 1.0
    intel_density = round(avg_completion / meta["model_size_gb"], 3) if meta["model_size_gb"] > 0 else 0.0

    # 4. Construct benchmark row
    benchmark_row = [
        meta["display_name"],
        meta["company"],
        meta["parent_model"],
        meta["model_quant"],
        meta["kv_quant"],
        meta["param_size_b"],
        meta["model_size_gb"],
        meta["context_length"],
        meta["release_date"],
        suite_trace["start_time"],
        "vLLM",
        meta["speculative_decoding"],
        harness_name,
        harness_version,
        "high",
        meta["launch_config"],
        avg_completion,
        task_speed,
        intel_density,
        test_results_summary,
    ]

    # 5. Save results.json
    results_record = {
        "eval_name": eval_name,
        "model": model_name,
        "harness": harness_name,
        "harness_version": harness_version,
        "timestamp": suite_trace["start_time"],
        "benchmark_row": benchmark_row,
        "test_results": test_results_summary,
    }
    results_path = os.path.join(eval_dir, "results.json")
    with open(results_path, "w", encoding="utf-8") as f:
        json.dump(results_record, f, indent=2)

    # 6. Update site/data/benchmark-data.json
    if os.path.exists(BENCHMARK_FILE):
        try:
            with open(BENCHMARK_FILE, "r", encoding="utf-8") as f:
                bench_data = json.load(f)

            # Prepend newest benchmark row to rows
            rows = bench_data.get("rows", [])
            rows.insert(0, benchmark_row)
            bench_data["rows"] = rows

            with open(BENCHMARK_FILE, "w", encoding="utf-8") as f:
                json.dump(bench_data, f, indent=2)
                f.write("\n")
            print(f"✓ Updated benchmark dataset: {BENCHMARK_FILE}")
        except Exception as e:
            print(f"Warning: Could not update {BENCHMARK_FILE}: {e}", file=sys.stderr)

    print(f"\n======================================================================")
    print(f"EVALUATION RESULTS SAVED")
    print(f"Directory: {eval_dir}")
    print(f"  - results.json")
    print(f"  - full_trace.json")
    print(f"  - opencode_server.log")
    print(f"  - artifacts/ ({len(os.listdir(artifacts_dir))} item(s))")
    print(f"======================================================================\n")

    return eval_dir


# =====================================================================
# Main Execution Entry Point
# =====================================================================

def main():
    parser = argparse.ArgumentParser(description="Drive evaluation harness inside isolated Docker sandbox")
    parser.add_argument("model", help="Model name (e.g. qwen/Qwen3.6-27B-FP8)")
    parser.add_argument("--test", default="test0", help="Specific test to run (e.g. 'test0' or 'all')")
    parser.add_argument("--harness", default="opencode", help="Harness name (default: opencode)")
    parser.add_argument("--base-url", default=DEFAULT_LLM_BASE_URL, help=f"LLM base URL (default: {DEFAULT_LLM_BASE_URL})")
    args = parser.parse_args()

    # Determine harness version from harnesses.json
    harness_version = "1.18.18"
    if os.path.exists(HARNESSES_FILE):
        try:
            with open(HARNESSES_FILE, "r", encoding="utf-8") as f:
                h_info = json.load(f)
                for k, v in h_info.items():
                    if args.harness.lower() in k.lower():
                        harness_version = v.get("version", harness_version)
        except Exception:
            pass

    # Discover tests
    test_specs = []
    if args.test == "all":
        tests_dir = os.path.join(REPO_ROOT, "tests")
        for item in sorted(os.listdir(tests_dir)):
            run_file = os.path.join(tests_dir, item, "run.py")
            if os.path.isfile(run_file):
                test_specs.append((run_file, load_test_spec(run_file)))
    else:
        test_file = os.path.join(REPO_ROOT, "tests", args.test, "run.py")
        test_specs.append((test_file, load_test_spec(test_file)))

    print(f"======================================================================")
    print(f"RUNNING {args.harness.upper()} HARNESS FOR MODEL: {args.model}")
    print(f"Tests to execute: {[t[1].name for t in test_specs]}")
    print(f"======================================================================")

    # Provision sandbox
    ensure_sandbox()
    try:
        configure_opencode_in_sandbox(args.model, llm_base_url=args.base_url)

        # Run test suite
        evaluation_output = run_test_suite_on_agent(
            model_name=args.model,
            test_specs=test_specs,
            sandbox_name=SANDBOX_NAME,
        )

        # Save results, trace, artifacts and update benchmark-data.json
        save_evaluation_results(
            model_name=args.model,
            harness_name=args.harness,
            harness_version=harness_version,
            evaluation_output=evaluation_output,
        )
    finally:
        remove_sandbox()


if __name__ == "__main__":
    main()
