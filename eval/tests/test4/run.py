def _run_probe(workspace_dir: str, cases: list[tuple[str, str]], perft_cases: list[tuple[str, str, int]], timeout: int = 300) -> dict:
    """Run the agent's movegen module in an isolated subprocess and collect its answers."""
    script = (
        _PROBE_HEADER
        .replace("WORKSPACE = None", "WORKSPACE = %r" % workspace_dir, 1)
        .replace("CASES = None", "CASES = %r" % (cases,), 1)
        .replace("PERFT_CASES = None", "PERFT_CASES = %r" % (perft_cases,), 1)
    )
    # Make this process undumpable so the probed module cannot scrape the
    # expected fixtures out of our memory via /proc or process_vm_readv.
    try:
        import ctypes
        ctypes.CDLL(None).prctl(4, 0)  # PR_SET_DUMPABLE
    except Exception:
        pass

    try:
        res = subprocess.run(
            [sys.executable, "-I", "-"],
            input=script,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=workspace_dir,
        )
    except subprocess.TimeoutExpired:
        return {"fatal": "movegen did not finish within %ds" % timeout}
    except Exception as exc:
        return {"fatal": "%s: %s" % (type(exc).__name__, exc)}

    match = re.search(r"__CHESS_JSON__(.*?)__CHESS_END__", res.stdout, re.DOTALL)
    if not match:
        tail = (res.stderr or res.stdout or "").strip().splitlines()[-6:]
        return {"fatal": "movegen probe crashed: " + " | ".join(tail)}
    try:
        return json.loads(match.group(1))
    except Exception as exc:
        return {"fatal": "could not parse movegen output: %s" % exc}


def _check_category(category: str, perft_key: str | None, label: str):
    """Build a check that validates one feature group with exact move sets and perft counts."""

    def _validate(workspace_dir: str) -> tuple[bool, str]:
        module_path = os.path.join(workspace_dir, "movegen.py")
        if not os.path.isfile(module_path):
            return False, "movegen.py was not found in the workspace."

        entries = CHESS_DATA[category]
        cases = [("%s-%d" % (category, i), entry["fen"]) for i, entry in enumerate(entries)]
        expected = {cid: sorted(entry["moves"]) for (cid, _), entry in zip(cases, entries)}
        perft_entries = CHESS_DATA["perft"][perft_key] if perft_key else []
        perft_cases = [("perft-%d" % i, entry["fen"], entry["depth"]) for i, entry in enumerate(perft_entries)]

        result = _run_probe(workspace_dir, cases, perft_cases)
        if "fatal" in result:
            return False, "%s: %s" % (label, result["fatal"])

        failures: list[str] = []

        for cid, _ in cases:
            got = result.get("moves", {}).get(cid)
            if isinstance(got, dict):
                failures.append("%s raised %s" % (cid, got.get("error", "an error")))
                continue
            if got is None:
                failures.append("%s returned no answer" % cid)
                continue
            want = expected[cid]
            duplicates = len(got) - len(set(got))
            missing = sorted(set(want) - set(got))
            extra = sorted(set(got) - set(want))
            if duplicates or missing or extra:
                detail = []
                if missing:
                    detail.append("missing %s" % missing[:6])
                if extra:
                    detail.append("unexpected %s" % extra[:6])
                if duplicates:
                    detail.append("%d duplicate(s)" % duplicates)
                failures.append("%s: %s" % (cid, "; ".join(detail)))

        for cid, _, _ in perft_cases:
            got = result.get("perft", {}).get(cid)
            entry = next(e for i, e in enumerate(perft_entries) if "perft-%d" % i == cid)
            if isinstance(got, dict):
                failures.append("%s raised %s" % (cid, got.get("error", "an error")))
            elif not isinstance(got, int) or got != entry["nodes"]:
                failures.append("%s: expected %d nodes at depth %d, got %r" % (cid, entry["nodes"], entry["depth"], got))

        if failures:
            preview = " | ".join(failures[:4])
            more = "" if len(failures) <= 4 else " (+%d more)" % (len(failures) - 4)
            return False, "%s: %d of %d checks failed. %s%s" % (
                label, len(failures), len(cases) + len(perft_cases), preview, more,
            )

        return True, "%s: all %d positions and %d perft counts match." % (
            label, len(cases), len(perft_cases),
        )

    return custom_check(_validate)


